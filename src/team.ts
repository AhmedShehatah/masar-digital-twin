/** compound first names that must stay on one line ("عبد الرحمن", "منه الله") */
const JOINED = /^(عبد|منه|أبو|ابو)$/

/** splits a full name into the given name (+ father) and the rest of the lineage */
export function splitName(full: string): [string, string] {
  const w = full.split(/\s+/)
  let n = JOINED.test(w[0]) ? 3 : 2
  if (JOINED.test(w[n - 1] ?? '') && w.length > n) n++
  return [w.slice(0, n).join(' '), w.slice(n).join(' ')]
}
